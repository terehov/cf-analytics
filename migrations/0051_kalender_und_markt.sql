-- 0051 Kalender und Marktindex — der Massstab von aussen
--
-- ANLASS (11.08.2026): Fuer die Round-Table-Map galten drei Posten als
-- "nicht angebunden" und damit als offene Anfrage an Concept Family:
--
--   * Marktvergleich  ("fuer Umsatz gegen Gesamtmarkt Gastronomie
--     existiert keine Quelle")
--   * Feiertage und Ferien ("offene Daten und schnell ergaenzt")
--   * Vergleichstag-Logik aus Kapitel 7.1
--
-- Keiner davon ist eine Anfrage. Alle drei sind offene Daten, und diese
-- Migration holt sie herein. Was uebrig bleibt — lokale Events und
-- Wetter — steht weiter im Dokument, weil es dort hingehoert.
--
-- ---------------------------------------------------------------------
-- WOHER DAS BUNDESLAND KOMMT
--
-- Nicht aus dem Betriebsnamen und nicht geraten. manual.betrieb_standort
-- fuehrt fuer 60 Betriebe eine gepflegte PLZ und Koordinaten; die 44
-- verschiedenen PLZ sind am 11.08.2026 einzeln gegen api.zippopotam.us
-- aufgeloest worden, das je PLZ Ort, Bundesland UND Koordinaten liefert.
-- Die Koordinaten dienten als Gegenprobe gegen die bereits gepflegten —
-- 44 von 44 stimmten im Ort ueberein (eine Abweichung bei 68723, wo der
-- Dienst Plankstadt statt Schwetzingen nennt; dasselbe Bundesland).
--
-- Der Umweg ueber die PLZ statt ueber den Ortsnamen ist Absicht: fuenf
-- Betriebe heissen nach derselben Stadt, und "Alter Kranen GmbH" traegt
-- ueberhaupt keinen Ort im Namen. Die PLZ ist eindeutig.
--
-- ---------------------------------------------------------------------
-- WOHER DIE FEIERTAGE KOMMEN — und warum aus ZWEI Quellen
--
-- openholidaysapi.org liefert Feiertage und Schulferien je Bundesland
-- maschinenlesbar. Die Schulferien reichen dort bis 2017 zurueck, die
-- gesetzlichen Feiertage aber erst bis 2020. Unsere Umsatzhistorie
-- beginnt am 01.01.2018. Fuer 2018 und 2019 kommen die Feiertage
-- deshalb von feiertage-api.de. Die Spalte quelle sagt je Zeile, welche
-- es war — wer den Bruch nicht sieht, haelt zwei Jahre ohne Feiertage
-- fuer zwei Jahre ohne Feiertagswirkung.
--
-- ---------------------------------------------------------------------
-- WARUM EUROSTAT UND NICHT GENESIS
--
-- Vorgabe war Destatis Genesis, Tabelle 45213. Der Genesis-REST-Dienst
-- verlangt seit dem Wegfall des Gastzugangs eine Registrierung; ein
-- Aufruf ohne Anmeldung liefert eine HTML-Seite, keine Daten (geprueft
-- am 11.08.2026). Dieselbe Reihe steht bei Eurostat offen: sts_setu_m,
-- NACE I56 (Gastronomie), Deutschland, monatlich, kalenderbereinigt.
-- Quelldaten sind die des Statistischen Bundesamtes — Eurostat ist der
-- Verteilweg, nicht eine zweite Messung.
--
-- Beide Reihen werden gefuehrt, weil die Entscheidung real gegen nominal
-- noch aussteht und sie das Ergebnis umdreht:
--
--   Mai 2026 gegen Mai 2018 — nominal +19,4 Prozent, real -20,2 Prozent.
--
-- Unsere eigenen Umsaetze sind nominal. Wer sie gegen die reale Reihe
-- haelt, misst die Inflation mit und nennt sie Wachstum. Deshalb steht
-- in mart.markt_vergleich beides nebeneinander und keines allein.
-- =====================================================================


-- ---------------------------------------------------------------------
-- Nachschlagewerk PLZ -> Bundesland
--
-- Eigene Tabelle statt einer Spalte an manual.betrieb_standort: die
-- Zuordnung haengt an der PLZ, nicht am Betrieb. Zieht ein Betrieb um,
-- aendert sich seine PLZ, und das Bundesland folgt von selbst.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS manual.plz_bundesland (
  plz         text PRIMARY KEY,
  bundesland  text NOT NULL,
  kuerzel     text NOT NULL,
  erfasst_am  timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE manual.plz_bundesland IS
'PLZ auf Bundesland, aufgeloest gegen api.zippopotam.us am 11.08.2026. Deckt die 44 PLZ ab, '
'die in manual.betrieb_standort stehen — nicht ganz Deutschland. Ein neuer Standort mit neuer '
'PLZ braucht hier eine Zeile, sonst faellt er still aus jeder Feiertagsrechnung heraus. '
'Die Arbeitsliste dafuer ist mart.kalender_fehlend.';

COMMENT ON COLUMN manual.plz_bundesland.kuerzel IS
'Zweibuchstabiges Kuerzel (BW, BY, ...). Verbindet mit manual.feiertag und manual.schulferien.';


-- ---------------------------------------------------------------------
-- Gesetzliche Feiertage je Bundesland
--
-- Ein Feiertag ist fuer die Gastronomie kein Ausfalltag, sondern ein
-- anderer Tag: das Geschaeft verschiebt sich, es verschwindet nicht.
-- Genau deshalb darf ein Feiertag nicht als Vergleichstag dienen — und
-- genau deshalb wird er nicht aus den Daten geloescht.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS manual.feiertag (
  kuerzel  text NOT NULL,
  datum    date NOT NULL,
  name     text NOT NULL,
  quelle   text NOT NULL,
  PRIMARY KEY (kuerzel, datum, name)
);

CREATE INDEX IF NOT EXISTS feiertag_datum_idx ON manual.feiertag (datum);

COMMENT ON TABLE manual.feiertag IS
'Gesetzliche Feiertage je Bundesland, 2018 bis 2027. 2018/2019 von feiertage-api.de, '
'ab 2020 von openholidaysapi.org — openholidays reicht bei den Feiertagen nicht vor 2020 '
'zurueck, unsere Umsatzhistorie beginnt aber 2018. Die Spalte quelle haelt den Bruch fest.';


-- ---------------------------------------------------------------------
-- Schulferien je Bundesland
--
-- Als Zeitraum gefuehrt, nicht als Einzeltage: die Quelle liefert es so,
-- und ein Zeitraum laesst sich nicht versehentlich halb laden.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS manual.schulferien (
  kuerzel  text NOT NULL,
  von      date NOT NULL,
  bis      date NOT NULL,
  name     text NOT NULL,
  quelle   text NOT NULL,
  PRIMARY KEY (kuerzel, von, name),
  CONSTRAINT schulferien_zeitraum CHECK (bis >= von)
);

CREATE INDEX IF NOT EXISTS schulferien_zeitraum_idx ON manual.schulferien (kuerzel, von, bis);

COMMENT ON TABLE manual.schulferien IS
'Schulferien je Bundesland, 2017 bis 2027, aus openholidaysapi.org. Zeitraeume, keine '
'Einzeltage. Ferien wirken in der Gastronomie in beide Richtungen: Innenstadtlagen verlieren '
'Mittagsgeschaeft, Ausflugslagen gewinnen. Deshalb wird die Ferienlage nur AUSGEWIESEN, '
'nicht bereinigt.';


-- ---------------------------------------------------------------------
-- Marktindex Gastronomie
--
-- Eine Zeile je Monat, zwei Reihen nebeneinander. Kein "der" Index.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS manual.marktindex (
  monat          date PRIMARY KEY,
  index_nominal  numeric(8,2),
  index_real     numeric(8,2),
  basis          text NOT NULL,
  quelle         text NOT NULL,
  stand          date NOT NULL
);

COMMENT ON TABLE manual.marktindex IS
'Umsatzindex Gastronomie Deutschland, monatlich, Index 2021=100, kalenderbereinigt. '
'Quelle Eurostat sts_setu_m NACE I56 (Quelldaten Destatis); Genesis Tabelle 45213 waere '
'dieselbe Reihe, verlangt aber seit Wegfall des Gastzugangs eine Registrierung. '
'NOMINAL ist der Vergleichsmassstab fuer unsere Umsaetze — die sind ebenfalls nominal. '
'REAL steht daneben, damit sichtbar bleibt, wie viel des Wachstums Preis war.';

COMMENT ON COLUMN manual.marktindex.stand IS
'Abrufdatum. Die Reihe wird rueckwirkend revidiert; ohne Stand ist nicht nachvollziehbar, '
'gegen welche Fassung ein alter Report gerechnet hat.';


