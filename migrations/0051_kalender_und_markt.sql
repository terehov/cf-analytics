-- ---------------------------------------------------------------------
-- Arbeitsliste: wem fehlt der Kalender
--
-- Dieselbe Logik wie mart.nachbarschaft_fehlend. Eine Feiertagsrechnung,
-- die einen Betrieb still auslaesst, sieht aus wie eine, die ihn
-- beruecksichtigt hat.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW mart.kalender_fehlend AS
SELECT b.betrieb_key,
       b.name AS betrieb,
       CASE WHEN s.betrieb_key IS NULL THEN 'kein Standort gepflegt'
            WHEN p.plz IS NULL         THEN 'PLZ ' || s.plz || ' nicht in manual.plz_bundesland'
       END AS grund,
       u.letzter_umsatztag,
       u.umsatz_2026
  FROM core.betrieb b
  LEFT JOIN manual.betrieb_standort s ON s.betrieb_key = b.betrieb_key
  LEFT JOIN manual.plz_bundesland   p ON p.plz = s.plz
  JOIN LATERAL (SELECT max(geschaeftstag) FILTER (WHERE umsatz_netto > 0) AS letzter_umsatztag,
                       round(sum(umsatz_netto) FILTER (WHERE geschaeftstag >= DATE '2026-01-01')) AS umsatz_2026
                  FROM mart.umsatz_tag t WHERE t.betrieb_key = b.betrieb_key) u ON true
 WHERE p.plz IS NULL
   AND u.letzter_umsatztag IS NOT NULL
 ORDER BY u.umsatz_2026 DESC NULLS LAST;

COMMENT ON VIEW mart.kalender_fehlend IS
'Betriebe mit laufendem Umsatz, fuer die kein Bundesland ableitbar ist — nach Umsatz '
'sortiert, damit der teuerste Fall oben steht. Erwartung: leer.';


-- ---------------------------------------------------------------------
-- Kalender je Betrieb und Tag
--
-- Die Basis fuer alles Weitere. Ein Tag ist Feiertag, wenn er es IM
-- BUNDESLAND DES BETRIEBS ist — Fronleichnam ist in Bayern ein
-- Feiertag und in Sachsen keiner, und der Unterschied traegt in der
-- Gastronomie einen ganzen Tagesumsatz.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW mart.betrieb_kalender AS
SELECT bb.betrieb_key,
       bb.betrieb,
       bb.kuerzel AS bundesland_kuerzel,
       bb.bundesland,
       t.geschaeftstag,
       extract(isodow FROM t.geschaeftstag)::int AS wochentag_nr,
       to_char(t.geschaeftstag, 'TMDay')         AS wochentag,
       f.name  AS feiertag,
       sf.name AS schulferien,
       (f.name  IS NOT NULL) AS ist_feiertag,
       (sf.name IS NOT NULL) AS ist_schulferien
  FROM mart.betrieb_bundesland bb
  JOIN (SELECT DISTINCT geschaeftstag FROM mart.umsatz_tag) t ON true
  LEFT JOIN LATERAL (SELECT name FROM manual.feiertag f
                      WHERE f.kuerzel = bb.kuerzel AND f.datum = t.geschaeftstag LIMIT 1) f ON true
  LEFT JOIN LATERAL (SELECT name FROM manual.schulferien s
                      WHERE s.kuerzel = bb.kuerzel
                        AND t.geschaeftstag BETWEEN s.von AND s.bis LIMIT 1) sf ON true;

COMMENT ON VIEW mart.betrieb_kalender IS
'Je Betrieb und Geschaeftstag: Wochentag, Feiertag im eigenen Bundesland, Schulferien im '
'eigenen Bundesland. Grundlage fuer mart.vergleichstag. Nur Betriebe mit gepflegter PLZ.';


-- ---------------------------------------------------------------------
-- Der Vergleichstag (Kapitel 7.1 der Round-Table-Map)
--
-- "Gleicher Wochentag, Durchschnitt der letzten vier vergleichbaren
-- Tage, Feiertage ausgeschlossen."
--
-- DREI ENTSCHEIDUNGEN, die man der Zahl sonst nicht ansieht:
--
-- 1. Feiertage fliegen aus dem VERGLEICHSVORRAT, nicht aus dem Ergebnis.
--    Ein Feiertag bekommt weiterhin einen Vergleichswert — gebildet aus
--    den letzten vier normalen Tagen desselben Wochentags. Genau das ist
--    die Frage, die am Feiertag interessiert: wie viel mehr oder weniger
--    war es als an einem gewoehnlichen Samstag.
--
-- 2. Tage ohne Umsatz zaehlen nicht mit. Ein Ruhetag ist kein schwacher
--    Tag; er wuerde den Schnitt vierteln und den Folgetag glaenzen
--    lassen.
--
-- 3. Die Ferienlage wird AUSGEWIESEN, nicht bereinigt. Weicht sie ab,
--    steht das in ferien_abweichung. Ein Samstag in den Sommerferien
--    gegen vier Samstage in der Schulzeit ist ein schlechter Vergleich —
--    aber ob er verworfen wird, entscheidet der Fachbereich und nicht
--    diese Sicht. Wer stillschweigend bereinigt, verliert die Faelle,
--    in denen genau die Ferien die Erklaerung sind.
--
-- ZUR LAUFZEIT: die Sicht rechnet je Zeile vier Nachbartage nach. Fuer
-- einen Betrieb und einen Monat ist das sofort da, fuer alle Betriebe
-- ueber acht Jahre nicht. Immer auf betrieb_key oder geschaeftstag
-- filtern.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW mart.vergleichstag AS
WITH basis AS (
  SELECT k.betrieb_key,
         k.betrieb,
         k.geschaeftstag,
         k.wochentag_nr,
         k.wochentag,
         k.feiertag,
         k.ist_feiertag,
         k.ist_schulferien,
         u.umsatz_netto,
         u.gaeste,
         u.rechnungen
    FROM mart.betrieb_kalender k
    JOIN mart.umsatz_tag u
      ON u.betrieb_key = k.betrieb_key AND u.geschaeftstag = k.geschaeftstag
)
SELECT b.betrieb_key,
       b.betrieb,
       b.geschaeftstag,
       b.wochentag,
       b.feiertag,
       b.ist_schulferien,
       b.umsatz_netto,
       b.gaeste,
       v.tage                                   AS vergleichstage,
       round(v.umsatz_schnitt, 2)               AS umsatz_vergleich,
       round(v.gaeste_schnitt, 1)               AS gaeste_vergleich,
       CASE WHEN v.umsatz_schnitt > 0
            THEN round(100.0 * (b.umsatz_netto - v.umsatz_schnitt) / v.umsatz_schnitt, 1)
       END                                      AS abweichung_pct,
       v.ferien_abweichung,
       v.von                                    AS vergleich_von,
       v.bis                                    AS vergleich_bis
  FROM basis b
  LEFT JOIN LATERAL (
        SELECT count(*)                                             AS tage,
               avg(r.umsatz_netto)                                  AS umsatz_schnitt,
               avg(r.gaeste) FILTER (WHERE r.gaeste > 0)            AS gaeste_schnitt,
               count(*) FILTER (WHERE r.ist_schulferien
                                  IS DISTINCT FROM b.ist_schulferien) AS ferien_abweichung,
               min(r.geschaeftstag)                                 AS von,
               max(r.geschaeftstag)                                 AS bis
          FROM (SELECT r2.geschaeftstag, r2.umsatz_netto, r2.gaeste, r2.ist_schulferien
                  FROM basis r2
                 WHERE r2.betrieb_key   = b.betrieb_key
                   AND r2.wochentag_nr  = b.wochentag_nr
                   AND r2.geschaeftstag < b.geschaeftstag
                   AND NOT r2.ist_feiertag
                   AND r2.umsatz_netto  > 0
                 ORDER BY r2.geschaeftstag DESC
                 LIMIT 4) r
  ) v ON true;

COMMENT ON VIEW mart.vergleichstag IS
'Kapitel 7.1 der Round-Table-Map: jeder Tag gegen den Durchschnitt der letzten vier '
'gleichen Wochentage ohne Feiertag und ohne Ruhetag. abweichung_pct ist die Antwort auf '
'"war das ein guter Samstag". IMMER auf Betrieb oder Zeitraum filtern — die Sicht rechnet '
'je Zeile vier Nachbartage nach. Was hier NICHT drinsteckt: lokale Events und Wetter.';

COMMENT ON COLUMN mart.vergleichstag.vergleichstage IS
'Wie viele Tage der Schnitt tatsaechlich trug. Weniger als 4 heisst: am Anfang der Historie '
'oder nach einer laengeren Schliessung. Ein Vergleich aus einem Tag ist keiner.';

COMMENT ON COLUMN mart.vergleichstag.ferien_abweichung IS
'Wie viele der Vergleichstage eine andere Ferienlage hatten als der Tag selbst. 0 heisst '
'sauber vergleichbar, 4 heisst: der Tag liegt in den Ferien und die Vergleichstage nicht '
'(oder umgekehrt). Wird ausgewiesen, nicht bereinigt.';


-- ---------------------------------------------------------------------
-- Umsatz gegen Markt (Kapitel 1.1 und 9.2)
--
-- Der Index ist eine Indexreihe, kein Euro-Betrag. Vergleichbar wird er
-- erst als VERAENDERUNG gegen den Vorjahresmonat — und genau so wird
-- unser eigener Umsatz danebengestellt.
--
-- Vorzeichen lesen: delta_pp ist die Differenz in Prozentpunkten.
-- Positiv heisst, wir sind schneller gewachsen als der Markt. Bei
-- schrumpfendem Markt heisst positiv auch "weniger geschrumpft".
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW mart.markt_vergleich AS
WITH eigen AS (
  SELECT date_trunc('month', geschaeftstag)::date AS monat,
         sum(umsatz_netto)                        AS umsatz
    FROM mart.umsatz_tag
   GROUP BY 1
), eigen_vj AS (
  SELECT e.monat,
         e.umsatz,
         v.umsatz AS umsatz_vorjahr,
         CASE WHEN v.umsatz > 0
              THEN round(100.0 * (e.umsatz - v.umsatz) / v.umsatz, 1) END AS eigen_pct
    FROM eigen e
    LEFT JOIN eigen v ON v.monat = e.monat - INTERVAL '1 year'
), markt AS (
  SELECT m.monat,
         m.index_nominal,
         m.index_real,
         CASE WHEN v.index_nominal > 0
              THEN round(100.0 * (m.index_nominal - v.index_nominal) / v.index_nominal, 1) END AS markt_nominal_pct,
         CASE WHEN v.index_real > 0
              THEN round(100.0 * (m.index_real - v.index_real) / v.index_real, 1) END AS markt_real_pct,
         m.stand
    FROM manual.marktindex m
    LEFT JOIN manual.marktindex v ON v.monat = m.monat - INTERVAL '1 year'
)
SELECT e.monat,
       round(e.umsatz)          AS umsatz_netto,
       e.eigen_pct              AS wir_ggue_vorjahr_pct,
       k.markt_nominal_pct      AS markt_nominal_ggue_vorjahr_pct,
       k.markt_real_pct         AS markt_real_ggue_vorjahr_pct,
       round(e.eigen_pct - k.markt_nominal_pct, 1) AS delta_pp,
       k.stand                  AS marktindex_stand
  FROM eigen_vj e
  LEFT JOIN markt k USING (monat)
 ORDER BY e.monat;

COMMENT ON VIEW mart.markt_vergleich IS
'Kapitel 1.1 und 9.2: unser Umsatzwachstum gegen den Markt. delta_pp vergleicht gegen die '
'NOMINALE Marktreihe, weil unsere Umsaetze nominal sind. Die reale Reihe steht daneben und '
'beantwortet die andere Frage: wie viel davon war Preis. Der Marktindex endet einen bis zwei '
'Monate vor dem laufenden Monat — dann bleibt die Spalte leer, sie wird nicht fortgeschrieben.';
